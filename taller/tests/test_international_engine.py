"""
Tests for the International Content Engine.

Covers:
- Engine output correctness (language, substitutions, structure)
- HTTP 200 for all country × vertical combinations via landing_vertical view
- Landing URLs generated by get_hub_landing_urls
- No cross-contamination of language/terminology
"""

import pytest
from django.contrib.auth.models import AnonymousUser
from django.test import RequestFactory

from taller.country.engine import get_hub_landing_urls, get_landing_context
from taller.country.verticals import VERTICAL_CONTENT
from taller.views.landing_views import landing_vertical

COUNTRIES = ["cl", "ar", "pe", "mx", "us_en", "us_es", "br", "ec", "ve"]
VERTICALS = ["workshop", "parts", "salvage", "tire", "carwash"]


# ---------------------------------------------------------------------------
# Engine — structural completeness
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("country_key", COUNTRIES)
@pytest.mark.parametrize("vertical_key", VERTICALS)
def test_engine_returns_required_keys(country_key, vertical_key):
    ctx = get_landing_context(country_key, vertical_key)
    required = {
        "seo_title", "meta_description", "hero_h1", "hero_badge",
        "hero_cta_primary", "tw", "rubro_key", "language",
        "cta_mid_heading", "cta_final_heading", "cta_final_button",
    }
    missing = required - set(ctx.keys())
    assert not missing, f"{country_key}/{vertical_key} missing keys: {missing}"


@pytest.mark.parametrize("country_key", COUNTRIES)
@pytest.mark.parametrize("vertical_key", VERTICALS)
def test_engine_no_unresolved_placeholders(country_key, vertical_key):
    ctx = get_landing_context(country_key, vertical_key)
    string_vals = [v for v in ctx.values() if isinstance(v, str)]
    for val in string_vals:
        assert "{" not in val or "}" not in val or val.count("{") == val.count("}") == 0 or \
               not any(k in val for k in ["workshop_name", "plate_term", "city_1", "currency_code"]), \
               f"{country_key}/{vertical_key}: unresolved placeholder in '{val[:80]}'"


