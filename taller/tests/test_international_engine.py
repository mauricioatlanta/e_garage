def test_plate_term_substituted_in_step():
    ctx_cl = get_landing_context("cl", "workshop")
    ctx_pe = get_landing_context("pe", "workshop")
    step_cl = ctx_cl["steps"][0]["body"]
    step_pe = ctx_pe["steps"][0]["body"]
    assert "patente" in step_cl
    assert "placa" in step_pe


